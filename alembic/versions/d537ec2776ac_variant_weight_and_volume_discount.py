# Weight only where the name states it ("1 KİLO", "800 GR"); "26 ER" is a piece
# count, not a weight, so those stay NULL for an admin to fill in.
_KG = re.compile(r"(\d+(?:[.,]\d+)?)\s*(?:K[İI]LO|KG)\b", re.IGNORECASE)
_GR = re.compile(r"(\d+)\s*GR\b", re.IGNORECASE)

